// While loops in javascript
/*
    1. while loop :
        while(condtion){
            code..
        }
    2. do-while loop    (it will run the  loop atleast one time )
        do{
            code...
        } while(condition)      
*/

// while loop
let i = 0;
while(i < 10){
    console.log(i);
    i++;
}


// do-while loop
let j = 0;
do{
    console.log("the vale of j is : " , j);
    j++;
}while(j > 10)

// The above program will run only one time due to do-while loop since the condtion is false  

